CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    name VARCHAR(50) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    phone VARCHAR(30), region_province VARCHAR(50), region_city VARCHAR(50),
    class_no INTEGER, graduation_year INTEGER, role VARCHAR(30) NOT NULL,
    terms_agreed BOOLEAN NOT NULL, privacy_agreed BOOLEAN NOT NULL,
    sms_agreed BOOLEAN NOT NULL, email_agreed BOOLEAN NOT NULL,
    approved_by BIGINT REFERENCES users(id), approved_at TIMESTAMP,
    enabled BOOLEAN NOT NULL, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS alumni_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id), occupation VARCHAR(120),
    public_profile BOOLEAN NOT NULL, memo VARCHAR(200),
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP
);

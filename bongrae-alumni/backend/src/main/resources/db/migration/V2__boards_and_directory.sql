CREATE TABLE alumni_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL, class_no INTEGER NOT NULL CHECK (class_no > 0),
    user_id BIGINT UNIQUE REFERENCES users(id),
    source_note VARCHAR(300) NOT NULL, consent_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX alumni_records_lookup ON alumni_records(class_no, name);

CREATE TABLE board_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board VARCHAR(30) NOT NULL CHECK (board IN ('ANNOUNCEMENTS','EVENTS','GALLERY','AFFAIRS','FREE')),
    title VARCHAR(200) NOT NULL, body TEXT NOT NULL,
    author_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX board_posts_listing ON board_posts(board, created_at DESC, id DESC);
CREATE TABLE board_media (
    id UUID PRIMARY KEY, post_id BIGINT REFERENCES board_posts(id) ON DELETE CASCADE,
    uploader_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    filename VARCHAR(200) NOT NULL, content_type VARCHAR(50) NOT NULL,
    byte_size INTEGER NOT NULL CHECK (byte_size > 0 AND byte_size <= 16777216),
    content BYTEA NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX board_media_post ON board_media(post_id);
CREATE TABLE admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(40) NOT NULL, target_id BIGINT NOT NULL,
    detail VARCHAR(200) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
